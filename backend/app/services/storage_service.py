"""
Pluggable file storage.

- ``LocalStorageBackend``: files under STORAGE_DIR (development, tests, single-disk servers).
- ``S3StorageBackend``: any S3-compatible bucket -- Backblaze B2, Cloudflare R2, MinIO, AWS S3.
  Free-first: B2/R2 free allowances work, nothing here activates a paid service.

Storage keys are always generated by the server (``<uuid>.<ext>``, ``out_<uuid>.<ext>``) and
validated against a strict pattern, so user input can never address arbitrary paths/objects.
Processing engines need real files, so ``materialize()`` returns a local path (the file itself
for local storage, a downloaded copy inside the job's work directory for S3).
"""
import hashlib
import logging
import os
import re
import shutil
import tempfile
import uuid
from abc import ABC, abstractmethod
from typing import Optional, Tuple

from fastapi import UploadFile

from app.core.config import settings

logger = logging.getLogger(__name__)

_KEY_PATTERN = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_.-]{0,200}$")
_CHUNK = 1024 * 1024


def validate_key(storage_key: str) -> str:
    key = os.path.basename(storage_key or "")
    if key != storage_key or not _KEY_PATTERN.match(key) or ".." in key:
        raise ValueError("Unsafe or invalid storage key.")
    return key


class StorageBackend(ABC):
    name = "abstract"

    @abstractmethod
    def put_file(self, local_path: str, key: str, content_type: str) -> None: ...

    @abstractmethod
    def exists(self, key: str) -> bool: ...

    @abstractmethod
    def delete(self, key: str) -> None: ...

    @abstractmethod
    def materialize(self, key: str, work_dir: str) -> str:
        """Return a local filesystem path with the object's bytes."""

    def local_path(self, key: str) -> Optional[str]:
        """Direct path when the object lives on local disk, else None."""
        return None

    def presigned_url(self, key: str, filename: str, content_type: str, ttl_seconds: int) -> Optional[str]:
        return None


class LocalStorageBackend(StorageBackend):
    name = "local"

    def __init__(self, base_dir: str):
        self.base_dir = os.path.abspath(base_dir)
        os.makedirs(self.base_dir, exist_ok=True)

    def _path(self, key: str) -> str:
        key = validate_key(key)
        path = os.path.abspath(os.path.join(self.base_dir, key))
        if os.path.dirname(path) != self.base_dir:
            raise ValueError("Unsafe path traversal detected.")
        return path

    def put_file(self, local_path: str, key: str, content_type: str) -> None:
        dest = self._path(key)
        if os.path.abspath(local_path) != dest:
            shutil.copyfile(local_path, dest)

    def exists(self, key: str) -> bool:
        return os.path.exists(self._path(key))

    def delete(self, key: str) -> None:
        path = self._path(key)
        if os.path.exists(path):
            os.remove(path)

    def materialize(self, key: str, work_dir: str) -> str:
        path = self._path(key)
        if not os.path.exists(path):
            raise FileNotFoundError("The input file is no longer available in storage.")
        return path

    def local_path(self, key: str) -> Optional[str]:
        return self._path(key)


class S3StorageBackend(StorageBackend):
    name = "s3"

    def __init__(self, bucket: str, endpoint_url: str = "", region: str = "auto",
                 access_key_id: str = "", secret_access_key: str = "", key_prefix: str = "",
                 client=None):
        import boto3
        from botocore.config import Config

        self.bucket = bucket
        self.prefix = key_prefix or ""
        self.client = client or boto3.client(
            "s3",
            endpoint_url=endpoint_url or None,
            region_name=region or None,
            aws_access_key_id=access_key_id or None,
            aws_secret_access_key=secret_access_key or None,
            config=Config(signature_version="s3v4", s3={"addressing_style": "path"},
                          retries={"max_attempts": 3, "mode": "standard"}),
        )

    def _obj(self, key: str) -> str:
        return f"{self.prefix}{validate_key(key)}"

    def put_file(self, local_path: str, key: str, content_type: str) -> None:
        self.client.upload_file(local_path, self.bucket, self._obj(key), ExtraArgs={"ContentType": content_type})

    def exists(self, key: str) -> bool:
        from botocore.exceptions import ClientError

        try:
            self.client.head_object(Bucket=self.bucket, Key=self._obj(key))
            return True
        except ClientError as e:
            if e.response.get("Error", {}).get("Code") in ("404", "NoSuchKey", "NotFound"):
                return False
            raise

    def delete(self, key: str) -> None:
        self.client.delete_object(Bucket=self.bucket, Key=self._obj(key))

    def materialize(self, key: str, work_dir: str) -> str:
        if not self.exists(key):
            raise FileNotFoundError("The input file is no longer available in storage.")
        os.makedirs(work_dir, exist_ok=True)
        dest = os.path.join(work_dir, validate_key(key))
        self.client.download_file(self.bucket, self._obj(key), dest)
        return dest

    def presigned_url(self, key: str, filename: str, content_type: str, ttl_seconds: int) -> Optional[str]:
        safe_name = filename.replace('"', "").replace("\r", "").replace("\n", "")
        return self.client.generate_presigned_url(
            "get_object",
            Params={
                "Bucket": self.bucket,
                "Key": self._obj(key),
                # Server-derived type + forced download, even on the bucket's origin.
                "ResponseContentType": content_type,
                "ResponseContentDisposition": f'attachment; filename="{safe_name}"',
                "ResponseCacheControl": "private, max-age=0, no-store",
            },
            ExpiresIn=ttl_seconds,
        )


def build_backend() -> StorageBackend:
    if settings.STORAGE_BACKEND.strip().lower() == "s3":
        return S3StorageBackend(
            bucket=settings.S3_BUCKET,
            endpoint_url=settings.S3_ENDPOINT_URL,
            region=settings.S3_REGION,
            access_key_id=settings.S3_ACCESS_KEY_ID,
            secret_access_key=settings.S3_SECRET_ACCESS_KEY,
            key_prefix=settings.S3_KEY_PREFIX,
        )
    return LocalStorageBackend(settings.STORAGE_DIR)


def _sha256_file(path: str) -> str:
    hasher = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(_CHUNK), b""):
            hasher.update(chunk)
    return hasher.hexdigest()


class StorageService:
    def __init__(self, backend: Optional[StorageBackend] = None):
        self.backend = backend or build_backend()

    # Backwards-compatible attribute used by older code/tests
    @property
    def base_dir(self) -> str:
        return getattr(self.backend, "base_dir", "")

    def save_upload(self, upload_file: UploadFile) -> Tuple[str, int, str]:
        """
        Saves an uploaded file safely, enforcing size limits, extension whitelisting,
        non-empty payload check, and calculating SHA-256 checksum.
        Returns: (storage_key, size_in_bytes, checksum)
        """
        from app.core.media_types import mime_type_for

        raw_name = upload_file.filename or "uploaded_media"
        safe_filename = os.path.basename(raw_name)
        file_ext = os.path.splitext(safe_filename)[1].lower()

        if not file_ext or file_ext not in settings.ALLOWED_EXTENSIONS:
            allowed_list = ", ".join(sorted(settings.ALLOWED_EXTENSIONS))
            raise ValueError(
                f"File format '{file_ext}' is not supported. "
                f"Allowed formats: {allowed_list}"
            )

        storage_key = f"{uuid.uuid4().hex}{file_ext}"
        os.makedirs(settings.WORK_DIR, exist_ok=True)
        fd, tmp_path = tempfile.mkstemp(prefix="upload_", suffix=file_ext, dir=settings.WORK_DIR)

        hasher = hashlib.sha256()
        total_size = 0
        try:
            with os.fdopen(fd, "wb") as buffer:
                while chunk := upload_file.file.read(1024 * 64):
                    total_size += len(chunk)
                    if total_size > settings.MAX_UPLOAD_SIZE_BYTES:
                        raise ValueError(
                            f"File size exceeds maximum permitted limit of {settings.MAX_UPLOAD_SIZE_BYTES // (1024 * 1024)} MB."
                        )
                    hasher.update(chunk)
                    buffer.write(chunk)

            if total_size == 0:
                raise ValueError("Uploaded file is empty (0 bytes). Please upload a valid media file.")

            self.backend.put_file(tmp_path, storage_key, mime_type_for(storage_key))
        finally:
            if os.path.exists(tmp_path):
                os.remove(tmp_path)

        return storage_key, total_size, hasher.hexdigest()

    def store_file(self, local_path: str, extension: str, prefix: str = "out_") -> Tuple[str, int, str]:
        """Persist a locally produced file. Returns (storage_key, size, checksum)."""
        from app.core.media_types import mime_type_for

        ext = extension if extension.startswith(".") else f".{extension}"
        storage_key = f"{prefix}{uuid.uuid4().hex}{ext.lower()}"
        size = os.path.getsize(local_path)
        checksum = _sha256_file(local_path)
        self.backend.put_file(local_path, storage_key, mime_type_for(storage_key))
        return storage_key, size, checksum

    def write_output_file(self, content_bytes: bytes, extension: str = ".txt") -> Tuple[str, int, str]:
        os.makedirs(settings.WORK_DIR, exist_ok=True)
        fd, tmp_path = tempfile.mkstemp(prefix="out_", suffix=extension, dir=settings.WORK_DIR)
        try:
            with os.fdopen(fd, "wb") as f:
                f.write(content_bytes)
            return self.store_file(tmp_path, extension)
        finally:
            if os.path.exists(tmp_path):
                os.remove(tmp_path)

    def get_full_path(self, storage_key: str) -> str:
        """Local filesystem path (local backend only)."""
        path = self.backend.local_path(storage_key)
        if path is None:
            raise ValueError("Direct file paths are not available for remote storage; use materialize().")
        return path

    def materialize(self, storage_key: str, work_dir: str) -> str:
        return self.backend.materialize(storage_key, work_dir)

    def exists(self, storage_key: str) -> bool:
        return self.backend.exists(storage_key)

    def delete(self, storage_key: str) -> None:
        self.backend.delete(storage_key)


storage_service = StorageService()
